// gen-redirects — writes the generated half of public/_redirects from the built pages.
//
//   npm run build && npm run redirects     then commit public/_redirects
//
// Every page offers a language picker (the locales), a version picker (the archived snapshots) and
// hreflang alternates, whether or not the page exists there. This lists, from dist/, what the
// pickers can offer that was never built, and sends each URL to the page that exists:
//   · the locale roots /es … /zh answer 301 to /es/ … instead of the platform's 307;
//   · the REST references (OPENAPI_BASES) exist only in English and only in the latest version,
//     so one splat rule per locale/snapshot prefix covers their ~800 generated pages;
//   · any other page a snapshot lacks goes to the same page in the same locale, else English.
// The hand-written rules stay outside the two marker lines. The platform counts every rule after
// the first wildcard rule as dynamic and ignores the rules past the 100th, so every exact rule goes
// first (the hand-written ones above the block, this block's exact rules first) and every wildcard
// rule after (this block's splats, then the hand-written ones below it).
// `npm run test:redirects` fails when a new page leaves a picker URL without a rule, which is the
// reminder to run this again.

import { readdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { ARCHIVED_SLUGS, OPENAPI_BASES, PUBLISHED_LOCALES } from '../src/site-locales.mjs'

const DIST = fileURLToPath(new URL('../dist', import.meta.url))
const FILE = fileURLToPath(new URL('../public/_redirects', import.meta.url))
const BEGIN = '# --- begin generated by scripts/gen-redirects.mjs (npm run redirects); edit nothing up to the end marker ---'
const END = '# --- end generated ---'

async function* walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = `${dir}/${e.name}`
    if (e.isDirectory()) yield* walk(p)
    else yield p
  }
}

/** The URL of the page at this locale ('' = English) and snapshot ('' = latest). */
const urlOf = (loc, ver, slug) => {
  const path = [loc, ver, slug].filter(Boolean).join('/')
  return path ? `/${path}/` : '/'
}

/** Splits a built URL into its locale, snapshot and the slug every copy of the page shares. */
function split(url) {
  const parts = url.split('/').filter(Boolean)
  const loc = PUBLISHED_LOCALES.includes(parts[0]) ? parts.shift() : ''
  const ver = ARCHIVED_SLUGS.includes(parts[0]) ? parts.shift() : ''
  return { loc, ver, slug: parts.join('/') }
}

const isApi = (slug) => OPENAPI_BASES.some((b) => slug === b || slug.startsWith(`${b}/`))

const pages = new Set()
for await (const f of walk(DIST)) {
  if (f.endsWith('/index.html')) pages.add(f.slice(DIST.length, -'index.html'.length))
}
if (pages.size === 0) {
  console.error('gen-redirects: no built pages in dist/; run npm run build first')
  process.exit(2)
}

const slugs = [...new Set([...pages].map((u) => split(u).slug))].sort()
const locs = ['', ...PUBLISHED_LOCALES]
const vers = ['', ...ARCHIVED_SLUGS]
const copies = locs.flatMap((loc) => vers.map((ver) => ({ loc, ver }))).filter((c) => c.loc || c.ver)

const exact = PUBLISHED_LOCALES.map((l) => `/${l} /${l}/ 301`)
const splats = []
for (const base of OPENAPI_BASES) {
  for (const { loc, ver } of copies) splats.push(`${urlOf(loc, ver, base)}* /${base}/:splat 301`)
}
for (const slug of slugs.filter((s) => !isApi(s))) {
  for (const { loc, ver } of copies) {
    const url = urlOf(loc, ver, slug)
    if (pages.has(url)) continue
    const successor = [urlOf(loc, '', slug), urlOf('', ver, slug), urlOf('', '', slug)].find((u) => pages.has(u))
    if (!successor) throw new Error(`gen-redirects: no page to send ${url} to`)
    exact.push(`${url} ${successor} 301`)
  }
}

const rules = [...exact, ...splats]
const current = await readFile(FILE, 'utf8')
const [head, rest] = current.split(BEGIN)
const tail = rest?.split(END)[1]
if (tail === undefined) throw new Error(`gen-redirects: ${FILE} needs the begin and end marker lines`)
await writeFile(FILE, `${head}${BEGIN}\n${rules.join('\n')}\n${END}${tail}`)
console.log(`gen-redirects: ${rules.length} generated rules (${exact.length} exact, ${splats.length} splat) from ${pages.size} built pages -> public/_redirects`)
