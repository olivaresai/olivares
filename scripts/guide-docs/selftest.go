// stage1Cases runs the dumper for real. `script` is passed in by the wrapper rather than
// guessed from the working directory: a path this program guessed wrong would make every
// case below unrunnable, and an unrunnable case that reports itself as skipped is the
// silent pass this battery exists to prevent. Hence — no skip. If the script or node is
// not there, these are FAILURES.
func stage1Cases(base, script string) []caseResult {
	var out []caseResult
	if script == "" || !fileExists(script) {
		return []caseResult{{name: "stage1/script-found", wantRC: 0, gotRC: 1,
			out: fmt.Sprintf("console-dump.mjs was not at %q, so stage 1's refusals were never executed. "+
				"Pass -stage1 <path>; the wrapper does.", script)}}
	}
	if _, err := exec.LookPath("node"); err != nil {
		return []caseResult{{name: "stage1/node-available", wantRC: 0, gotRC: 1,
			out: "no node on PATH, so stage 1's refusals were never executed"}}
	}
	// <root>/scripts/guide-docs/console-dump.mjs -> <root>/web/node_modules
	repoRoot := filepath.Dir(filepath.Dir(filepath.Dir(script)))

	mk := func(name string, mutate func(dir string) error) (string, error) {
		dir := filepath.Join(base, "s1-"+name)
		if err := write(dir, "web/src/features/registry.tsx", stage1RegistrySrc("'a:b:read'")); err != nil {
			return "", err
		}
		if err := write(dir, "web/src/app/routes.tsx", stage1Routes); err != nil {
			return "", err
		}
		if err := write(dir, censusRel, stage1Census()); err != nil {
			return "", err
		}
		// The compiler the console is built with. The fixture borrows the real tree's
		// node_modules by symlink rather than shipping a second copy.
		if realWeb := filepath.Join(repoRoot, "web", "node_modules"); fileExists(realWeb) {
			_ = os.Symlink(realWeb, filepath.Join(dir, "web", "node_modules"))
		}
		if mutate != nil {
			if err := mutate(dir); err != nil {
				return "", err
			}
		}
		return dir, nil
	}
	run1 := func(name string, wantRC int, needle string, mutate func(string) error) {
		dir, err := mk(name, mutate)
		if err != nil {
			out = append(out, caseResult{name: "stage1/" + name, wantRC: wantRC, gotRC: -1, out: err.Error()})
			return
		}
		cmd := exec.Command("node", script, "--root", dir)
		combined, _ := cmd.CombinedOutput()
		rc := cmd.ProcessState.ExitCode()
		out = append(out, caseResult{name: "stage1/" + name, wantRC: wantRC, gotRC: rc, needle: needle, out: string(combined)})
	}

	// GREEN: a tiny but well-formed console dumps, and the entry hidden inside a comment
	// is NOT in it — the whole reason this stage uses a compiler.
	run1("well-formed-console-dumps", 0, `"path": "/beta"`, nil)

	// RED: the registry stopped being an array literal, so nothing could be enumerated.
	run1("registry-is-not-an-array", 2, "not as an array literal", func(dir string) error {
		return write(dir, "web/src/features/registry.tsx",
			"export const HUB_ORDER: HubId[] = ['operate']\nexport const FEATURE_VIEWS: FeatureView[] = buildViews()\n")
	})

	// RED: the roster shrank to a handful. A dumper that emitted it would let the Go half
	// regenerate a four-screen console over a fifty-screen one and call it in sync.
	run1("roster-below-the-population-floor", 2, "not a console", func(dir string) error {
		return write(dir, "web/src/features/registry.tsx",
			"export const HUB_ORDER: HubId[] = ['operate']\nexport const FEATURE_VIEWS: FeatureView[] = [\n"+
				"  { id: 'alpha', path: '/alpha', hub: 'operate', helpHref: '/x', element: lazyView(A) },\n]\n")
	})

	// RED: a permission written as an expression. "Computed and unreadable" must never
	// collapse into "this view needs no permission" — they are opposite facts.
	run1("permission-is-a-computed-expression", 2, "non-literal expression", func(dir string) error {
		return write(dir, "web/src/features/registry.tsx", stage1RegistrySrc("PERMS.alpha"))
	})

	// RED: the census went missing. Without it there is no roster to cover.
	run1("census-missing", 2, "no route roster", func(dir string) error {
		return os.Remove(filepath.Join(dir, censusRel))
	})
	return out
}

