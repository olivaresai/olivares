// The battery that proves this gate can fail.
//
// Every trap the generator exists to catch is planted on a throwaway repository and must
// produce the RIGHT answer — not merely a non-zero one. The three verdicts are distinct on
// purpose (0 in sync / 1 drift / 2 CANNOT LOOK), so each case asserts the exact code AND,
// for the red ones, that the offender is NAMED in the output. "It went red" is not
// evidence: a gate that fails for the wrong reason satisfies a whole red column while
// checking nothing.
//
// The GREEN cases are not filler either. Without them a gate that failed unconditionally
// would pass every red case above and be indistinguishable from a working one.
//
// The fixtures are whole small repositories, not mocks: the same loaders, the same parsers
// and the same renderer run over them as over the real tree. A battery that exercised a
// simplified path would prove that the simplified path works.

