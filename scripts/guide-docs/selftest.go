// The registry fixture clears the dumper's own population floor (its whole job is to
// refuse a roster that is too small to be a console), and carries the two shapes that
// matter: an entry hidden inside a COMMENT, which a compiler must not see, and one entry
// whose permission is absent rather than computed.
