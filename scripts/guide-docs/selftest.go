// The generated registration table, in the shape protoc-gen-go emits. 22 unary methods
// plus 3 streams across two files puts the fixture above the gRPC floor.
func fixtureGRPCFile(pkg, svcPrefix, metadata string, n int, withStream bool) (gen string, rpcs int) {
	var iface, desc, streams strings.Builder
	fmt.Fprintf(&iface, "type %sClient interface {\n", svcPrefix)
	for i := 0; i < n; i++ {
		fmt.Fprintf(&iface, "\tCall%02d(ctx context.Context, in *Req%02d, opts ...grpc.CallOption) (*Resp%02d, error)\n", i, i, i)
		fmt.Fprintf(&desc, "\t\t{\n\t\t\tMethodName: \"Call%02d\",\n\t\t\tHandler:    _h,\n\t\t},\n", i)
		rpcs++
	}
	if withStream {
		fmt.Fprintf(&iface, "\tWatch(ctx context.Context, in *WatchRequest, opts ...grpc.CallOption) (grpc.ServerStreamingClient[Tick], error)\n")
		fmt.Fprintf(&iface, "\tFeed(ctx context.Context, opts ...grpc.CallOption) (grpc.ClientStreamingClient[Item, Receipt], error)\n")
		streams.WriteString("\t\t{\n\t\t\tStreamName:    \"Watch\",\n\t\t\tHandler:       _h,\n\t\t\tServerStreams: true,\n\t\t},\n")
		streams.WriteString("\t\t{\n\t\t\tStreamName:    \"Feed\",\n\t\t\tHandler:       _h,\n\t\t\tClientStreams: true,\n\t\t},\n")
		rpcs += 2
	}
	iface.WriteString("}\n")
	gen = fmt.Sprintf(`// Code generated by protoc-gen-go-grpc. DO NOT EDIT.

package genpb

import (
	context "context"
	grpc "google.golang.org/grpc"
)

%s
var %s_ServiceDesc = grpc.ServiceDesc{
	ServiceName: %q,
	HandlerType: (*%sServer)(nil),
	Methods: []grpc.MethodDesc{
%s	},
	Streams: []grpc.StreamDesc{
%s	},
	Metadata: %q,
}
`, iface.String(), svcPrefix, pkg+"."+svcPrefix, svcPrefix, desc.String(), streams.String(), metadata)
	return gen, rpcs
}

// fixtureProto is only ever read for the rpc CROSS-CHECK, so it carries the declarations
// and nothing else. The comment and the string literal are there on purpose: they mention
// `rpc` in places a grep would count and a token scan must not.
func fixtureProto(svc string, n int, withStream bool) string {
	var b strings.Builder
	b.WriteString("syntax = \"proto3\";\n\n")
	b.WriteString("// This comment says rpc Decoy(Empty) returns (Empty); and must not be counted.\n")
	b.WriteString("option go_package = \"example/genpb\";\n")
	b.WriteString("option (note) = \"rpc Ghost(Empty) returns (Empty);\";\n\n")
	fmt.Fprintf(&b, "service %s {\n", svc)
	for i := 0; i < n; i++ {
		fmt.Fprintf(&b, "  rpc Call%02d(Req%02d) returns (Resp%02d);\n", i, i, i)
	}
	if withStream {
		b.WriteString("  rpc Watch(WatchRequest) returns (stream Tick);\n")
		b.WriteString("  rpc Feed(stream Item) returns (Receipt);\n")
	}
	b.WriteString("}\n")
	return b.String()
}

